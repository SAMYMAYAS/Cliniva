from pathlib import Path
import json
p=Path('standalone/neuro-atlas')
s=json.loads((p/'evidence/callouts-delivery.json').read_text(encoding='utf-8'))
a=s['actions']
def click(id,selector):a.append(dict(step_id=id,action='click',locator=dict(kind='css',selector=selector)))
def fill(id,selector,value):a.append(dict(step_id=id,action='fill',locator=dict(kind='css',selector=selector),value=dict(source='literal',value=value)))
def press(id,selector,key):a.append(dict(step_id=id,action='press',locator=dict(kind='css',selector=selector),key=key))
def cut(n):fill('slice'+str(n),'#slice',str(n));press('apply'+str(n),'#slice','Tab')
click('edit-old','.external-label[data-annotation-id="video-v1-s05-01"]')
click('delete-old','#delete-annotation')
click('restore-old','#restore-deleted')
cut(16)
click('edit-new','.external-label[data-annotation-id="screenshot-v1-43-20"]')
fill('new-name','#label-input','Pédoncule cérébelleux supérieur · test')
click('save-new','#annotation-form .primary')
a.append(dict(step_id='reload',action='goto',destination=dict(url='http://127.0.0.1:4177'),wait_until='load'))
cut(16)
click('read-after-reload','.external-label[data-annotation-id="screenshot-v1-43-20"]')
fill('restore-name','#label-input','Pédoncule cérébelleux supérieur')
click('save-restored-name','#annotation-form .primary')
click('review-source','#review-list button:first-child')
click('close-review','#close-review')
click('enable-regions','#regions')
cut(13)
press('opacity-end','#region-opacity','End')
click('quiz','#quiz')
click('reveal','.external-label[data-annotation-id="screenshot-v1-65-00"]')
click('end-quiz','#quiz')
press('opacity-home','#region-opacity','Home')
for i in range(32):press('opacity'+str(i),'#region-opacity','ArrowRight')
a.append(dict(step_id='settled',action='wait_for_timeout',duration_ms=600))
s['capture']['after_each_step']=['accessibility']
(p/'evidence/screenshots-qa.json').write_text(json.dumps(s,ensure_ascii=False,indent=2),encoding='utf-8')
